TITLE = "Политика обработки персональных данных"


def render_text(op: dict) -> str:
    out = [f"{TITLE}\nсервиса «{SERVICE}»\nРедакция от {EDITION}\n"]
    for heading, paras in sections(op):
        out.append(heading)
        out.extend(paras)
        out.append("")
    return "\n".join(out).strip() + "\n"


def render_html(op: dict) -> str:
    e = html.escape
    body = [f"<h1>{e(TITLE)}</h1>", f"<p class=\"meta\">Сервис «{e(SERVICE)}» · редакция от {e(EDITION)}</p>"]
    for heading, paras in sections(op):
        body.append(f"<h2>{e(heading)}</h2>")
        body.extend(f"<p>{e(p)}</p>" for p in paras)
    return (
        "<!doctype html>\n<html lang=\"ru\"><head><meta charset=\"utf-8\">"
        "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
        f"<title>{e(TITLE)}</title>"
        "<style>:root{color-scheme:light dark}body{font:16px/1.55 -apple-system,system-ui,sans-serif;"
        "max-width:720px;margin:0 auto;padding:16px 16px 48px}h1{font-size:1.4rem}h2{font-size:1.1rem;margin-top:1.6em}"
        ".meta{opacity:.7}</style></head><body>" + "".join(body) + "</body></html>"
    )


def chunks(text: str, limit: int = 4000) -> list[str]:
    """Режет текст по строкам на части, которые принимает Telegram (лимит 4096)."""
    parts, cur = [], ""
    for line in text.splitlines(keepends=True):
        while len(line) > limit:  # очень длинная строка — режем жёстко
            if cur:
                parts.append(cur)
                cur = ""
            parts.append(line[:limit])
            line = line[limit:]
        if len(cur) + len(line) > limit:
            parts.append(cur)
            cur = ""
        cur += line
    if cur:
        parts.append(cur)
    return parts


_PLACEHOLDER = "example.com"


def link(policy_url: str, webapp_url: str) -> str:
    """Куда ведёт кнопка «Политика»: свой POLICY_URL, иначе своя страница /policy, иначе пусто (покажем в чате)."""
    if policy_url and _PLACEHOLDER not in policy_url:
        return policy_url
    return f"{webapp_url.rstrip('/')}/policy" if webapp_url else ""


def current_link() -> str:
    from config import config
    return link(config.policy_url, config.webapp_url)


