    """Что сказать, когда адрес не нашёлся: по возможности объясняем, где он на самом деле."""
    if diag and diag.where:
        out = (f"Такой адрес есть на карте, но он в другом месте: {diag.where}. "
               "Мы работаем только в Москве и Московской области.")
        if diag.town:
            out += (f" Если вы имели в виду {diag.town} в Москве или области, напишите так: "
                    f"{diag.town}, улица, дом.")
        else:
            out += " Напишите адрес в Москве или области: город, улица, дом."
        return out
    if diag and diag.town:
        return (f"Населённый пункт {diag.town} нашла, а такой улицы с домом там не нашла. "
                "Проверьте название улицы и номер дома и напишите ещё раз: город, улица, дом. "
                "Или нажмите «Ввести заново» и отправьте точку на карте.")
    return ADDR_NOT_FOUND if fails < 2 else ADDR_NOT_FOUND_KEEP


