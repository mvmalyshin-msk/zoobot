def menu_text(last: dict | None) -> str:
    """Приветствие в меню с подсказкой, какой заказ был последним (клиент мог забыть)."""
    if not last:
        return WELCOME
    from utils import fmt_local
    pet = f" · {last['pet_name']}" if last.get("pet_name") else ""
    return (f"{WELCOME}\n\nПоследний заказ: {last['name']} · {fmt_local(last['start_at'])}{pet} · "
            f"{STATUS_LABELS[last['status']]}")


_PAID = _re.compile(r"^(?:я\s+)?(?:оплатил[аи]?|оплата\s+прошла|перевёл|перевел|перевела)(?:\s+деньги)?[\s.!]*$", _re.I)


def is_paid_claim(text: str) -> bool:
    """Клиент пишет «оплатил» — это сообщение «я заплатил», его нужно передать админу на проверку."""
    return bool(_PAID.match(" ".join((text or "").split())))


