def variant_label(category: str, name: str) -> str:
    """«Выгул 30 минут» → «30 минут», «Передержка в частном доме» → «В частном доме»."""
    word = _CATEGORY_WORD.get(category, "")
    rest = name[len(word):].strip() if word and name.lower().startswith(word) else name
    return (rest[:1].upper() + rest[1:]) if rest else name


